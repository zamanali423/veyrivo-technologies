/**
 * Generates premium placeholder team portraits for the About page.
 *
 * The team members are fictional, so instead of shipping stock photos
 * (licensing) or hotlinking external avatar services (unreliable), this
 * script renders deterministic on-brand duotone "portrait" art with sharp
 * and emits:
 *   - public/images/team/<slug>.webp   (480x480 source image)
 *   - src/content/team-photos.ts       (src + width/height + base64 blurDataURL)
 *
 * To use REAL headshots later: drop photos into public/images/team/ named
 * <slug>.jpg (or .png/.webp), update PHOTOS.srcPath below, and re-run
 * `node scripts/generate-team-photos.mjs` to regenerate blur placeholders.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/** slug -> { accentA, accentB, srcPath (source photo or null) } */
const PHOTOS = {
  "muhammad-shahid": { a: "#2f80ed", b: "#00c2ff", srcPath: null },
  "zaman-ali": { a: "#00c2ff", b: "#8b5cf6", srcPath: null },
  "muhammad-abiid": { a: "#8b5cf6", b: "#2f80ed", srcPath: null },
};

const SIZE = 480;

function svgArt(slug, { a, b }) {
  const lines = [];
  for (let x = 40; x < SIZE; x += 40) lines.push(`M ${x} 0 V ${SIZE}`);
  for (let y = 40; y < SIZE; y += 40) lines.push(`M 0 ${y} H ${SIZE}`);
  return `
<svg width="${SIZE}" height="${SIZE}" viewBox="0 0 ${SIZE} ${SIZE}" xmlns="http://www.w3.org/2000/svg">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#0d1524"/>
      <stop offset="1" stop-color="#06090f"/>
    </linearGradient>
    <radialGradient id="halo" cx="0.5" cy="0.38" r="0.55">
      <stop offset="0" stop-color="${a}" stop-opacity="0.55"/>
      <stop offset="1" stop-color="${a}" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="bust" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="${a}"/>
      <stop offset="1" stop-color="${b}"/>
    </linearGradient>
    <linearGradient id="rim" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#eaf1fb"/>
      <stop offset="0.6" stop-color="#9db4d4"/>
      <stop offset="1" stop-color="#4c5f7e"/>
    </linearGradient>
    <radialGradient id="vig" cx="0.5" cy="0.5" r="0.75">
      <stop offset="0.6" stop-color="#000000" stop-opacity="0"/>
      <stop offset="1" stop-color="#000000" stop-opacity="0.6"/>
    </radialGradient>
    <filter id="grain">
      <feTurbulence type="fractalNoise" baseFrequency="0.9" numOctaves="2" stitchTiles="stitch"/>
      <feColorMatrix type="saturate" values="0"/>
    </filter>
  </defs>

  <rect width="${SIZE}" height="${SIZE}" fill="url(#bg)"/>
  <g stroke="#ffffff" stroke-opacity="0.035" stroke-width="1">${lines.join("")}</g>
  <circle cx="240" cy="176" r="250" fill="url(#halo)"/>

  <path d="M 92 480 C 92 372 150 318 210 296 L 210 268 C 210 222 224 176 240 162 C 256 176 270 222 270 268 L 270 296 C 330 318 388 372 388 480 Z" fill="url(#bust)"/>
  <path d="M 92 480 C 92 372 150 318 210 296 L 210 268 C 210 222 224 176 240 162" fill="none" stroke="url(#rim)" stroke-width="3" stroke-linecap="round"/>
  <circle cx="240" cy="240" r="224" fill="none" stroke="${a}" stroke-opacity="0.35" stroke-width="1.5"/>

  <rect width="${SIZE}" height="${SIZE}" filter="url(#grain)" opacity="0.05"/>
  <rect width="${SIZE}" height="${SIZE}" fill="url(#vig)"/>
</svg>`;
}

async function main() {
  const outDir = join(root, "public", "images", "team");
  mkdirSync(outDir, { recursive: true });

  const entries = [];
  for (const [slug, cfg] of Object.entries(PHOTOS)) {
    let src = cfg.srcPath
      ? readFileSync(join(root, cfg.srcPath))
      : Buffer.from(svgArt(slug, cfg));
    let meta;
    if (cfg.srcPath) {
      // Real photo: center-crop to square, then resize.
      meta = await sharp(src)
        .resize(SIZE, SIZE, { fit: "cover", position: "attention" })
        .webp({ quality: 88 })
        .toFile(join(outDir, `${slug}.webp`));
    } else {
      meta = await sharp(src)
        .webp({ quality: 88 })
        .toFile(join(outDir, `${slug}.webp`));
    }

    // Tiny blurred thumbnail for next/image placeholder="blur".
    const blur = await sharp(src)
      .resize(24, 24, { fit: cfg.srcPath ? "cover" : "fill", position: "attention" })
      .blur(12)
      .webp({ quality: 40 })
      .toBuffer();
    const blurDataURL = `data:image/webp;base64,${blur.toString("base64")}`;

    entries.push({
      slug,
      src: `/images/team/${slug}.webp`,
      width: SIZE,
      height: SIZE,
      blurDataURL,
    });
    console.log(`${slug}.webp  ${meta.width}x${meta.height}  ${(meta.size / 1024).toFixed(1)}KB  blur ${blur.length}B`);
  }

  const ts = `/* AUTO-GENERATED by scripts/generate-team-photos.mjs — do not edit by hand.
   Regenerate with: node scripts/generate-team-photos.mjs */
import type { TeamPhoto } from "@/content/team";

export const teamPhotos: Record<string, TeamPhoto> = {
${entries
  .map(
    (e) => `  ${JSON.stringify(e.slug)}: {
    src: ${JSON.stringify(e.src)},
    width: ${e.width},
    height: ${e.height},
    blurDataURL: ${JSON.stringify(e.blurDataURL)},
  },`,
  )
  .join("\n")}
};
`;

  const tsPath = join(root, "src", "content", "team-photos.ts");
  writeFileSync(tsPath, ts);
  console.log(`\nWrote ${tsPath}`);
  console.log(`Wrote ${entries.length} images to ${outDir}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
